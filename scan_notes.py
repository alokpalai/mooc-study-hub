"""Scan notes/*.pdf in natural order and (re)write notes.js, keeping any existing summary/concepts."""
import json, re, pathlib

root = pathlib.Path(__file__).parent
notes_dir = root / "notes"
js = root / "notes.js"

existing = {}
if js.exists():
    m = re.search(r"window\.NOTES\s*=\s*(\[.*\]);", js.read_text(encoding="utf-8"), re.S)
    if m:
        existing = {n["file"]: n for n in json.loads(m.group(1))}

def natural(p):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", p.name)]

notes = []
for p in sorted(notes_dir.glob("*.pdf"), key=natural):
    old = existing.get(p.name, {})
    notes.append({
        "file": p.name,
        "title": old.get("title") or re.sub(r"[_-]+", " ", p.stem).strip(),
        "summary": old.get("summary", ""),
        "concepts": old.get("concepts", []),
    })

js.write_text(
    "// Generated by scan_notes.py — notes in reading order.\nwindow.NOTES = "
    + json.dumps(notes, indent=2, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"{len(notes)} note(s) written to notes.js")
